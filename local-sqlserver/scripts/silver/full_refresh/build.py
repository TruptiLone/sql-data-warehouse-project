#!/usr/bin/env python3
"""Compose preserved legacy transformations/checks into one transaction owner."""
import argparse
import hashlib
import re
from pathlib import Path

HERE=Path(__file__).resolve().parent
BASE=HERE.parent
TABLES={'crm_cust_info':18484,'crm_prd_info':397,'crm_sales_details':60398,
        'erp_cust_az12':18484,'erp_loc_a101':18484,'erp_px_cat_g1v2':37}
SOURCES=['load_crm.sql','load_sales.sql','load_erp.sql','quality_checks.sql','quality_sales.sql','quality_erp.sql',
         'ddl_crm.sql','ddl_sales.sql','ddl_erp.sql']

def body(name):
    s=(BASE/name).read_text()
    s=s.split('BEGIN TRANSACTION;',1)[1].rsplit('COMMIT TRANSACTION;',1)[0]
    s=s.replace('SYSDATETIME()', '@load_time').replace('GETDATE()', '@load_time')
    if name=='load_sales.sql': s=s.replace('@existing','@sales_existing')
    # Only orchestration predicates change; transformations/expected comparisons remain intact.
    s=re.sub(r'IF @(?:sales_)?existing=0', 'IF @execute_refresh=1',s)
    s=re.sub(r'IF NOT EXISTS\(SELECT 1 FROM silver\.(erp_\w+)\)', 'IF @execute_refresh=1',s)
    return s

def quality(name,marker):
    s=(BASE/name).read_text()
    return s[s.index(marker):].replace('GETDATE()', '@load_time')

def build():
    hashes='\n'.join('-- '+n+' sha256='+hashlib.sha256((BASE/n).read_bytes()).hexdigest() for n in SOURCES)
    header='''-- GENERATED by full_refresh/build.py. Do not edit generated SQL directly.
-- Existing transformation files remain unchanged. Rebuild after reviewed rule changes.
'''+hashes+'''
:ON ERROR EXIT
USE [DataWarehouse];
GO
CREATE OR ALTER PROCEDURE silver.refresh_all
 @expected_machine sysname,
 @execute_refresh bit=0,
 @confirmation nvarchar(100)=NULL,
 @inject_failure varchar(30)=NULL
AS
BEGIN
 SET NOCOUNT ON;
 SET XACT_ABORT ON;
 -- Reject caller-owned transactions: this procedure alone owns commit/rollback.
 IF @@TRANCOUNT<>0 THROW 51300,'Run refresh_all outside any existing transaction.',1;
 IF DB_NAME()<>'DataWarehouse' OR CONVERT(int,SERVERPROPERTY('EngineEdition'))<>3
  OR CONVERT(nvarchar(128),SERVERPROPERTY('Edition')) NOT LIKE N'Developer Edition%'
  OR @expected_machine IS NULL OR @expected_machine<>CONVERT(sysname,SERVERPROPERTY('MachineName'))
  OR CONVERT(varchar(48),CONNECTIONPROPERTY('local_net_address'))<>'127.0.0.1'
  OR CONNECTIONPROPERTY('local_net_address') IS NULL
  THROW 51301,'Expected verified local Docker Developer DataWarehouse over loopback TCP.',1;
 IF @execute_refresh IS NULL THROW 51302,'Refresh mode must be explicit.',1;
 IF @execute_refresh=1 AND ISNULL(@confirmation,N'')<>N'REFRESH SIX LOCAL SILVER TABLES'
  THROW 51303,'Explicit local Silver refresh confirmation is required.',1;
 IF @inject_failure IS NOT NULL AND (@execute_refresh=0 OR @inject_failure NOT IN ('after_truncate','validation'))
  THROW 51304,'Unsupported failure-test mode.',1;
 DECLARE @load_time datetime2(7)=SYSDATETIME(),@run_id uniqueidentifier=NEWID(),@lock_result int,@locked_rows bigint;
 DECLARE @targets TABLE(table_name sysname PRIMARY KEY,expected_rows bigint);
 INSERT @targets VALUES
'''+',\n'.join(f"('{n}',{v})" for n,v in TABLES.items())+''';
 BEGIN TRY
  BEGIN TRANSACTION;
  EXEC @lock_result=sys.sp_getapplock @Resource=N'RetailFlow360.Silver.FullRefresh',
   @LockMode='Exclusive',@LockOwner='Transaction',@LockTimeout=10000;
  IF @lock_result<0 THROW 51305,'Another refresh owns the application lock; no refresh performed.',1;
  IF EXISTS(SELECT 1 FROM @targets WHERE OBJECT_ID(N'silver.'+table_name,'U') IS NULL
   OR OBJECT_ID(N'bronze.'+table_name,'U') IS NULL)
   THROW 51306,'All six Bronze and Silver tables must already exist.',1;
  -- Emptying children does NOT remove SQL Server TRUNCATE FK restrictions.
  IF EXISTS(SELECT 1 FROM sys.foreign_keys WHERE referenced_object_id IN
   (SELECT OBJECT_ID(N'silver.'+table_name) FROM @targets))
   THROW 51307,'Foreign key references a refresh target; review strategy, never disable/drop constraints.',1;
  IF EXISTS(SELECT 1 FROM sys.triggers WHERE is_disabled=0 AND parent_id IN
   (SELECT OBJECT_ID(N'silver.'+table_name) FROM @targets))
   THROW 51308,'Enabled target triggers could write outside refresh scope; review required.',1;
  IF EXISTS(SELECT 1 FROM sys.tables WHERE object_id IN(SELECT OBJECT_ID(N'silver.'+table_name) FROM @targets)
   AND (temporal_type<>0 OR is_replicated=1 OR is_merge_published=1 OR is_tracked_by_cdc=1 OR is_memory_optimized=1))
   THROW 51309,'Unsupported target storage/replication feature.',1;
  IF EXISTS(SELECT 1 FROM sys.sql_expression_dependencies d JOIN sys.views v ON v.object_id=d.referencing_id
   JOIN sys.indexes i ON i.object_id=v.object_id AND i.index_id=1
   WHERE d.referenced_id IN(SELECT OBJECT_ID(N'silver.'+table_name) FROM @targets))
   THROW 51310,'Indexed view references a target; review required.',1;
'''
    # Schema contracts derived from existing local DDL, not untracked original files.
    specs=[]
    for filename in ['ddl_crm.sql','ddl_sales.sql','ddl_erp.sql']:
        for name,inside in re.findall(r'CREATE TABLE silver\.\[?(\w+)\]?\s*\((.*?)\);',(BASE/filename).read_text(),re.S):
            for i,(col,typ) in enumerate(re.findall(r'\[?(\w+)\]?\s+(NVARCHAR\(50\)|DATETIME2|DATE|INT)\s+NULL',inside),1):
                specs.append(f"('{name}',{i},'{col}','{typ.split('(')[0].lower()}',{ {'NVARCHAR(50)':100,'DATETIME2':8,'DATE':3,'INT':4}[typ] },{7 if typ=='DATETIME2' else 0})")
    assert len(specs)==39,len(specs)
    header+='DECLARE @schema_contract TABLE(t sysname,n int,c sysname,typ sysname,bytes smallint,scale tinyint);\nINSERT @schema_contract VALUES\n'+',\n'.join(specs)+';\n'
    actual="""SELECT t.name,c.column_id,c.name,TYPE_NAME(c.user_type_id),c.max_length,c.scale,CONVERT(int,c.is_nullable),CONVERT(int,c.is_identity),CONVERT(int,c.is_computed)
 FROM sys.tables t JOIN sys.columns c ON c.object_id=t.object_id WHERE t.schema_id=SCHEMA_ID('silver') AND t.name IN(SELECT table_name FROM @targets)"""
    wanted='SELECT t,n,c,typ,bytes,scale,1,0,0 FROM @schema_contract'
    header+=f"IF EXISTS({actual} EXCEPT {wanted}) OR EXISTS({wanted} EXCEPT {actual}) THROW 51311,'Target schema differs from reviewed 39-column contract.',1;\n"
    for name in TABLES:
        header+=f'SELECT @locked_rows=COUNT_BIG(*) FROM bronze.{name} WITH(TABLOCK,HOLDLOCK);\n'
    for name in TABLES:
        header+=f'SELECT @locked_rows=COUNT_BIG(*) FROM silver.{name} WITH(TABLOCKX,HOLDLOCK);\n'
    header+='''
 IF @execute_refresh=1
 BEGIN
'''
    for name in ['crm_sales_details','erp_cust_az12','erp_loc_a101','erp_px_cat_g1v2','crm_prd_info','crm_cust_info']:
        header+=f'  TRUNCATE TABLE silver.{name};\n'
    header+=" END;\n IF @inject_failure='after_truncate' THROW 51390,'Controlled failure after all six truncations.',1;\n"
    result=header
    for source in ['load_crm.sql','load_sales.sql','load_erp.sql']:
        result+='\n-- Preserved transformation and expected-result checks: '+source+'\n'+body(source)
    for source,marker in [('quality_checks.sql','DECLARE @failures'),('quality_sales.sql','DECLARE @checks'),('quality_erp.sql',"SELECT 'birthdates")]:
        result+='\n-- Formerly post-commit; now inside the refresh transaction: '+source+'\n'+quality(source,marker)
    result+='''
 -- New full-refresh integration gates; known category discrepancy is a warning.
 IF EXISTS(SELECT 1 FROM silver.erp_cust_az12 e WHERE NOT EXISTS(SELECT 1 FROM silver.crm_cust_info c WHERE c.cst_key=e.cid))
 OR EXISTS(SELECT 1 FROM silver.erp_loc_a101 e WHERE NOT EXISTS(SELECT 1 FROM silver.crm_cust_info c WHERE c.cst_key=e.cid))
 OR EXISTS(SELECT 1 FROM silver.crm_cust_info c WHERE NOT EXISTS(SELECT 1 FROM silver.erp_cust_az12 e WHERE e.cid=c.cst_key))
 OR EXISTS(SELECT 1 FROM silver.crm_cust_info c WHERE NOT EXISTS(SELECT 1 FROM silver.erp_loc_a101 e WHERE e.cid=c.cst_key))
  THROW 51312,'CRM/ERP customer/location coverage failed.',1;
 IF EXISTS(SELECT 1 FROM silver.erp_loc_a101 WHERE cntry NOT IN ('Australia','Canada','France','Germany','United Kingdom','United States','n/a'))
  THROW 51313,'Country domain changed; review required.',1;
 -- Fixed snapshot acceptance contract in addition to source-derived reconciliation.
 -- Inject an incorrect expectation to exercise the REAL critical validation path.
 IF @inject_failure='validation' UPDATE @targets SET expected_rows=expected_rows+1 WHERE table_name='erp_px_cat_g1v2';
'''
    for name in TABLES:
        result+=f"IF (SELECT COUNT_BIG(*) FROM silver.{name})<>(SELECT expected_rows FROM @targets WHERE table_name='{name}') THROW 51391,'Critical snapshot row-count validation failed.',1;\n"
        result+=f"IF @execute_refresh=1 AND EXISTS(SELECT 1 FROM silver.{name} WHERE dwh_create_date IS NULL OR dwh_create_date<>@load_time) THROW 51314,'Inconsistent full-refresh timestamp.',1;\n"
    result+='''
 COMMIT TRANSACTION;
 SELECT @run_id AS run_id,@execute_refresh AS refreshed,@load_time AS load_time,
  CASE WHEN @execute_refresh=1 THEN 'COMMITTED' ELSE 'PREVIEW PASSED: no Silver writes' END AS status;
 END TRY
 BEGIN CATCH
  IF XACT_STATE()<>0 ROLLBACK TRANSACTION;
  SELECT @run_id AS run_id,'ROLLED BACK / NOT COMMITTED' AS status,ERROR_NUMBER() AS error_number,
   ERROR_PROCEDURE() AS error_procedure,ERROR_LINE() AS error_line,ERROR_MESSAGE() AS error_message;
  THROW;
 END CATCH;
END;
GO
'''
    return "\n".join(line.rstrip() for line in result.splitlines())+"\n"

if __name__=='__main__':
    parser=argparse.ArgumentParser();parser.add_argument('--check',action='store_true');args=parser.parse_args()
    output=HERE/'refresh_all.sql';text=build()
    if args.check:
        if not output.exists() or output.read_text()!=text: raise SystemExit('Generated procedure differs; rebuild and review.')
        print('PASS: generated procedure matches preserved source loaders, checks and DDL.')
    else:
        output.write_text(text);print(f'Wrote {output.name}; no SQL executed.')
